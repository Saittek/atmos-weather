const catalogs: Record<LocaleId, Record<ModeKey, string>> = {
  en: { ...en },
  fr: { ...fr },
}

export function te(
  locale: LocaleId,
  key: ModeKey,
  vars?: Record<string, string | number>,
): string {
  const raw = catalogs[locale]?.[key] ?? catalogs.en[key] ?? key
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (_, k: string) =>
    vars[k] != null ? String(vars[k]) : `{${k}}`,
  )
}
