/**
 * Rewrite ios/App/CapApp-SPM/Package.swift with paths/package IDs that work on
 * Codemagic macOS + modern SwiftPM (Xcode 15–26).
 *
 * Why: Capacitor may emit `.package(name: "Foo", path: "...")` or Windows
 * backslashes. On newer Xcode the `name:` for local packages is ignored and the
 * package identity becomes the last path component (e.g. "app", "solara-widget"),
 * so `.product(..., package: "CapacitorApp")` fails during archive (exit 65).
 *
 * Run after `npx cap sync ios`.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkgPath = path.join(root, 'ios', 'App', 'CapApp-SPM', 'Package.swift')

/** Local Capacitor plugins: product name → path relative to CapApp-SPM */
const localPackages = [
  {
    // identity = last path segment = solara-widget
    identity: 'solara-widget',
    product: 'SolaraWidget',
    relPath: '../../../plugins/solara-widget',
  },
  { identity: 'app', product: 'CapacitorApp', relPath: '../../../node_modules/@capacitor/app' },
  { identity: 'browser', product: 'CapacitorBrowser', relPath: '../../../node_modules/@capacitor/browser' },
  {
    identity: 'geolocation',
    product: 'CapacitorGeolocation',
    relPath: '../../../node_modules/@capacitor/geolocation',
  },
  { identity: 'haptics', product: 'CapacitorHaptics', relPath: '../../../node_modules/@capacitor/haptics' },
  { identity: 'keyboard', product: 'CapacitorKeyboard', relPath: '../../../node_modules/@capacitor/keyboard' },
  {
    identity: 'local-notifications',
    product: 'CapacitorLocalNotifications',
    relPath: '../../../node_modules/@capacitor/local-notifications',
  },
  {
    identity: 'push-notifications',
    product: 'CapacitorPushNotifications',
    relPath: '../../../node_modules/@capacitor/push-notifications',
  },
  {
    identity: 'splash-screen',
    product: 'CapacitorSplashScreen',
    relPath: '../../../node_modules/@capacitor/splash-screen',
  },
  {
    identity: 'status-bar',
    product: 'CapacitorStatusBar',
    relPath: '../../../node_modules/@capacitor/status-bar',
  },
]

function assertExists(relFromRoot) {
  const abs = path.join(root, relFromRoot)
  if (!fs.existsSync(abs)) {
    throw new Error(`Missing package path: ${relFromRoot} (resolved ${abs})`)
  }
  if (!fs.existsSync(path.join(abs, 'Package.swift'))) {
    throw new Error(`Missing Package.swift under ${relFromRoot}`)
  }
}

// Validate from repo root
assertExists('plugins/solara-widget')
for (const p of localPackages) {
  if (p.relPath.includes('node_modules')) {
    const fromRoot = p.relPath.replace(/^\.\.\/\.\.\/\.\.\//, '')
    assertExists(fromRoot)
  }
}

const depLines = [
  '        .package(url: "https://github.com/ionic-team/capacitor-swift-pm.git", exact: "8.4.1"),',
  ...localPackages.map(
    (p) => `        .package(path: "${p.relPath}"), // identity: ${p.identity}`,
  ),
]

const productLines = [
  '                .product(name: "Capacitor", package: "capacitor-swift-pm"),',
  '                .product(name: "Cordova", package: "capacitor-swift-pm"),',
  ...localPackages.map(
    (p) => `                .product(name: "${p.product}", package: "${p.identity}"),`,
  ),
]

const contents = `// swift-tools-version: 5.9
import PackageDescription

// GENERATED by scripts/fix-ios-spm-paths.mjs after \`cap sync\` — do not hand-edit.
// Local package identity = last path component (required by modern SwiftPM / Xcode 26).
let package = Package(
    name: "CapApp-SPM",
    platforms: [.iOS(.v15)],
    products: [
        .library(
            name: "CapApp-SPM",
            targets: ["CapApp-SPM"])
    ],
    dependencies: [
${depLines.join('\n')}
    ],
    targets: [
        .target(
            name: "CapApp-SPM",
            dependencies: [
${productLines.join('\n')}
            ]
        )
    ]
)
`

fs.mkdirSync(path.dirname(pkgPath), { recursive: true })
fs.writeFileSync(pkgPath, contents, 'utf8')
console.log(`Wrote ${path.relative(root, pkgPath)}`)
for (const p of localPackages) {
  console.log(`  ${p.product} <- package "${p.identity}" @ ${p.relPath}`)
}
